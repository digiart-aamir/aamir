            (function() {
                // 1. Live Islamabad Clock (PKT / UTC+5)
                function updateIslamabadClock() {
                    const clockEl = document.getElementById('islamabad-clock');
                    const statusTextEl = document.getElementById('availability-status-text');
                    if (!clockEl) return;

                    try {
                        const now = new Date();
                        // Get PKT time (Asia/Karachi timezone)
                        const options = {
                            timeZone: 'Asia/Karachi',
                            hour: '2-digit',
                            minute: '2-digit',
                            second: '2-digit',
                            hour12: true
                        };
                        const timeString = new Intl.DateTimeFormat('en-US', options).format(now);
                        clockEl.textContent = timeString + ' PKT';

                        // Calculate hour in PKT for office status
                        const pktHourStr = new Intl.DateTimeFormat('en-US', {
                            timeZone: 'Asia/Karachi',
                            hour: 'numeric',
                            hour12: false
                        }).format(now);
                        const pktHour = parseInt(pktHourStr, 10);

                        if (statusTextEl) {
                            if (pktHour >= 8 && pktHour < 22) {
                                statusTextEl.textContent = 'In Office & Active';
                            } else {
                                statusTextEl.textContent = 'Available (Fast Reply)';
                            }
                        }
                    } catch (e) {
                        clockEl.textContent = 'Islamabad (UTC+5)';
                    }
                }

                updateIslamabadClock();
                setInterval(updateIslamabadClock, 1000);
            })();

            // 2. One-Click Email Copy
            function copyContactEmail(btn) {
                const email = 'digiart.aamir@gmail.com';
                navigator.clipboard.writeText(email).then(() => {
                    const originalHTML = btn.innerHTML;
                    btn.innerHTML = `
                        <svg class="w-3 h-3 text-emerald-600" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2.5" d="M5 13l4 4L19 7"/>
                        </svg>
                        <span class="text-emerald-700 font-bold">Copied!</span>
                    `;
                    btn.classList.add('bg-emerald-50', 'border-emerald-300');
                    if (typeof showNotification === 'function') {
                        showNotification('Email address copied to clipboard: ' + email, 'success');
                    }
                    setTimeout(() => {
                        btn.innerHTML = originalHTML;
                        btn.classList.remove('bg-emerald-50', 'border-emerald-300');
                    }, 2200);
                }).catch(() => {
                    window.location.href = 'mailto:' + email;
                });
            }

            // 3. Topic Pill Selector
            function selectContactTopic(button, topicName) {
                const subjectField = document.getElementById('subject-field');
                const allPills = document.querySelectorAll('.interest-pill');

                // Toggle active state
                const isActive = button.classList.contains('active-pill');
                allPills.forEach(p => {
                    p.classList.remove('active-pill', 'bg-gradient-to-r', 'from-indigo-600', 'to-purple-600', 'text-white', 'border-transparent', 'shadow-sm');
                    p.classList.add('bg-gray-50/70', 'dark:bg-gray-800/50', 'text-gray-700', 'dark:text-gray-300', 'border-gray-200', 'dark:border-gray-700');
                });

                if (!isActive) {
                    button.classList.add('active-pill', 'bg-gradient-to-r', 'from-indigo-600', 'to-purple-600', 'text-white', 'border-transparent', 'shadow-sm');
                    button.classList.remove('bg-gray-50/70', 'dark:bg-gray-800/50', 'text-gray-700', 'dark:text-gray-300', 'border-gray-200', 'dark:border-gray-700');

                    if (subjectField) {
                        const currentVal = subjectField.value.trim();
                        // If empty or previously auto-filled, set clean topic subject
                        if (!currentVal || currentVal.startsWith('[')) {
                            subjectField.value = `[${topicName}] Project Inquiry`;
                        } else {
                            subjectField.value = `[${topicName}] ` + currentVal.replace(/^\[.*?\]\s*/, '');
                        }
                    }
                } else if (subjectField && subjectField.value.startsWith(`[${topicName}]`)) {
                    subjectField.value = subjectField.value.replace(`[${topicName}] `, '').replace(`[${topicName}]`, '');
                }
            }

            // 4. Live Character Counter
            function updateContactCharCount(textarea) {
                const counter = document.getElementById('char-counter');
                if (!counter) return;
                const len = textarea.value.length;
                counter.textContent = `${len} / 1000`;
                if (len > 900) {
                    counter.classList.add('text-amber-500');
                } else {
                    counter.classList.remove('text-amber-500');
                }
            }

